/** Essence needed to advance from `level` to `level + 1`; null at the maximum level. */
export function essenceToNextLevel(level: number): number | null {
  if (!Number.isInteger(level) || level < 1 || level >= MAX_LEVEL) return null;
  return ESSENCE_TO_ADVANCE[level - 1] ?? null;
}

